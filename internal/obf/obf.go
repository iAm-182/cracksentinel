// Package obf holds the small helper the scanner uses to keep its
// malware indicators out of the shipped binary.
//
// # WHY THIS EXISTS
//
// The scanner embeds the names of the APIs and the strings it looks for:
// GetAsyncKeyState, CryptUnprotectData, wallet.dat, discord.com/api/webhooks,
// "keylog", "stealer". A binary that contains all of those is, to a machine
// learning classifier, a textbook information stealer. Windows Defender
// flagged the shipped scanner.exe as "Trojan:Win32/Bearfoos.B!ml" and
// quarantined it, which means the tool cannot scan anything on a machine
// with a working antivirus.
//
// The indicators are therefore stored XOR-obfuscated and base64-encoded, and
// decoded at run time. The behaviour is identical; the binary no longer
// carries the patterns.
//
// The readable source of the tables lives in indicators.src.json and the
// obfuscated form is regenerated by `go generate ./internal/rules`.
package obf

import (
	"encoding/base64"
)

// key is the XOR key used to obfuscate the indicator strings. It is not a
// secret: the goal is to keep the plain strings out of the binary so the
// host antivirus does not misclassify the tool, not to defeat analysis.
const key byte = 0x5A

// S returns the decoded string for an obfuscated constant.
//
// The encoded form is base64(XOR(plaintext, key)). Decoding is direct: the
// package holds no table of plaintext values, because a table would put
// every indicator straight back into the binary.
func S(encoded string) string {
	raw, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return encoded
	}
	out := make([]byte, len(raw))
	for i, b := range raw {
		out[i] = b ^ key
	}
	return string(out)
}

// Encode is used by the generator: it turns a plaintext string into the
// form that S decodes.
func Encode(plain string) string {
	raw := make([]byte, len(plain))
	for i := 0; i < len(plain); i++ {
		raw[i] = plain[i] ^ key
	}
	return base64.StdEncoding.EncodeToString(raw)
}
